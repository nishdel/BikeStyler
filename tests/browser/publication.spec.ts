import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';

test('public bicycle example preserves its design, saves, exports white and reopens offline', async ({page, context}, info) => {
  test.setTimeout(120000);
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${process.env.BIKESTYLER_PREVIEW_PORT || '4173'}/`);
  await page.getByLabel('Import portable project').setInputFiles('public/sample/champagne.bike.json');
  await expect(page.getByRole('heading',{name:'Champagne bicycle',exact:true})).toBeVisible();
  await expect(page.locator('.save-status')).toHaveText('Saved locally');
  await expect(page.locator('.app-footer')).toContainText('Ready offline',{timeout:45000});
  const dismiss=page.getByRole('button',{name:'Dismiss message'});if(await dismiss.count())await dismiss.click();
  const capture=async(name:string)=>{if(process.env.BIKESTYLER_CAPTURE_DOCS)await page.screenshot({path:`docs/images/${name}.png`});};
  await page.locator('canvas').first().waitFor();
  await page.getByRole('button',{name:'Markers',exact:false}).click();
  await capture('editor');
  await page.locator('.component-strip button').filter({hasText:'Saddle'}).click();
  await page.getByRole('button',{name:'Real parts',exact:true}).click();
  await expect(page.locator('.product-visual-card').filter({hasText:'B17'})).toHaveClass(/active/);
  await capture('components');
  await page.getByRole('button',{name:/Compare/}).click();
  await expect(page.getByText('Slide to compare',{exact:true})).toBeVisible();
  await capture('comparison');
  await page.getByRole('button',{name:'Style',exact:true}).click();
  await page.getByRole('button',{name:'Catalogue',exact:true}).click();
  await expect(page.locator('.product-card').first()).toBeVisible();
  await capture('catalogue');
  await page.getByRole('button',{name:'Close catalogue'}).click();
  const saved=page.waitForEvent('download');await page.getByRole('button',{name:'Save editable project ↓'}).click();
  const portable=info.outputPath('example.bike.json');await(await saved).saveAs(portable);
  const p=JSON.parse(await fs.readFile(portable,'utf8'));
  expect(p.styles.saddle.entryId).toBe('photo-brooks-b17');
  expect(p.designs.length).toBeGreaterThan(1);
  await page.getByLabel('Import portable project').setInputFiles(portable);
  await expect(page.locator('.save-status')).toHaveText('Saved locally');
  await context.setOffline(true);await page.reload();
  await expect(page.locator('.garage')).toBeVisible();
  const exported=page.waitForEvent('download');await page.getByRole('button',{name:/Export PNG/}).click();
  const png=info.outputPath('white.png');await(await exported).saveAs(png);
  const data='data:image/png;base64,'+(await fs.readFile(png)).toString('base64');
  const pixels=await page.evaluate(async(data)=>{const im=new Image();im.src=data;await im.decode();const c=document.createElement('canvas');c.width=im.width;c.height=im.height;const ctx=c.getContext('2d')!;ctx.drawImage(im,0,0);const d=ctx.getImageData(0,0,c.width,c.height).data;let transparent=0;for(let i=3;i<d.length;i+=4)if(d[i]!==255)transparent++;return{corner:[...d.slice(0,4)],transparent};},data);
  expect(pixels).toEqual({corner:[255,255,255,255],transparent:0});
  expect(errors).toEqual([]);await context.setOffline(false);
});
